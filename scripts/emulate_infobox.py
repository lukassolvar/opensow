#!/usr/bin/env python3
"""Runs the exe's info-box stat code (unit/weapon construction 0x469f80/0x46bd30, offence 0x46b440, 0x4099a0, aircraft 0x467ee0)
in an x86 emulator and prints the values the info box shows (docs/hud.md). The exe is only read.
  python3 -m venv v && v/bin/pip install unicorn pefile && v/bin/python scripts/emulate_infobox.py "State of War.exe"
"""
import struct, sys, pefile
from unicorn import *
from unicorn.x86_const import *
exe=sys.argv[1]  # usage: python3 scripts/emulate_infobox.py "State of War.exe"
pe=pefile.PE(exe); base=pe.OPTIONAL_HEADER.ImageBase
mu=Uc(UC_ARCH_X86,UC_MODE_32)
size=(pe.OPTIONAL_HEADER.SizeOfImage+0xfff)&~0xfff
mu.mem_map(base,size)
for s in pe.sections: mu.mem_write(base+s.VirtualAddress,s.get_data())
STACK=0x70000000; HEAP=0x60000000; RET=0x50000000
mu.mem_map(STACK,0x200000); mu.mem_map(HEAP,0x4000000); mu.mem_map(RET,0x1000); mu.mem_write(RET,b"\xf4")
TEB=0x40000000; mu.mem_map(TEB,0x10000)
# GDT with one data segment whose base is the TEB, loaded into FS (32-bit mode has no FS_BASE register)
GDT=0x41000000; mu.mem_map(GDT,0x1000)
def desc(base_,limit,access,flags): return struct.pack('<HHBBBB',limit&0xffff,base_&0xffff,(base_>>16)&0xff,access,((limit>>16)&0xf)|(flags<<4),(base_>>24)&0xff)
mu.mem_write(GDT+8*5,desc(TEB,0xfff,0x93,0x4))
mu.mem_write(GDT+8*2,desc(0,0xfffff,0x93,0xc))
mu.reg_write(UC_X86_REG_GDTR,(0,GDT,0x1000,0))
for r in (UC_X86_REG_DS,UC_X86_REG_ES,UC_X86_REG_SS): mu.reg_write(r,2<<3)
mu.reg_write(UC_X86_REG_FS,5<<3)
heap=[HEAP+0x1000]
def alloc(n):
    p=heap[0]; heap[0]+=(n+15)&~15; return p
NEW=0x47d315
def hook(uc,addr,sz,ud):
    esp=uc.reg_read(UC_X86_REG_ESP)
    if addr in (NEW,0x47d31b):
        (ret,n)=struct.unpack('<II',uc.mem_read(esp,8))
        uc.reg_write(UC_X86_REG_EAX,alloc(n)); uc.reg_write(UC_X86_REG_ESP,esp+4); uc.reg_write(UC_X86_REG_EIP,ret)
def memset_hook(uc,addr,sz,ud):
    esp=uc.reg_read(UC_X86_REG_ESP)
    ret,p,v,n=struct.unpack('<IIII',uc.mem_read(esp,16))
    uc.mem_write(p,bytes([v&0xff])*n); uc.reg_write(UC_X86_REG_EAX,p); uc.reg_write(UC_X86_REG_ESP,esp+4); uc.reg_write(UC_X86_REG_EIP,ret)
def rand_hook(uc,addr,sz,ud):
    esp=uc.reg_read(UC_X86_REG_ESP); (ret,)=struct.unpack('<I',uc.mem_read(esp,4))
    uc.reg_write(UC_X86_REG_EAX,0); uc.reg_write(UC_X86_REG_ESP,esp+4); uc.reg_write(UC_X86_REG_EIP,ret)
mu.hook_add(UC_HOOK_CODE,rand_hook,begin=0x437b10,end=0x437b10)
mu.hook_add(UC_HOOK_CODE,memset_hook,begin=0x47edb4,end=0x47edb4)
mu.hook_add(UC_HOOK_CODE,hook,begin=NEW,end=0x47d31b)
def delete_hook(uc,addr,sz,ud):  # operator delete 0x47d30f: nothing to free in the arena
    esp=uc.reg_read(UC_X86_REG_ESP); (ret,)=struct.unpack('<I',uc.mem_read(esp,4))
    uc.reg_write(UC_X86_REG_ESP,esp+4); uc.reg_write(UC_X86_REG_EIP,ret)
mu.hook_add(UC_HOOK_CODE,delete_hook,begin=0x47d30f,end=0x47d30f)
def unmapped(uc,access,addr,size,value,ud):
    print('unmapped',access,hex(addr),'at',hex(uc.reg_read(UC_X86_REG_EIP)))
    return False
mu.hook_add(UC_HOOK_MEM_READ_UNMAPPED|UC_HOOK_MEM_WRITE_UNMAPPED,unmapped)
def call(addr,args=(),ecx=None,maxn=200000):
    sp=STACK+0x100000
    for a in reversed(args): sp-=4; mu.mem_write(sp,struct.pack('<I',a&0xffffffff))
    sp-=4; mu.mem_write(sp,struct.pack('<I',RET))
    mu.reg_write(UC_X86_REG_ESP,sp)
    if ecx is not None: mu.reg_write(UC_X86_REG_ECX,ecx)
    try: mu.emu_start(addr,RET,count=maxn)
    except UcError as e:
        print('ERR',e,hex(mu.reg_read(UC_X86_REG_EIP)),'ret',hex(rd32(mu.reg_read(UC_X86_REG_ESP)))); return None
    return mu.reg_read(UC_X86_REG_EAX)
def rd32(a): return struct.unpack('<I',mu.mem_read(a,4))[0]
def rds32(a): return struct.unpack('<i',mu.mem_read(a,4))[0]
def cstr(a):
    b=bytes(mu.mem_read(a,64)); return b.split(b'\0')[0]
if __name__ == '__main__':
    print("// generated by scripts/emulate_infobox.py: (kind, offence, defence, scope min, scope max, speed)")
    for kind in list(range(1, 16)) + list(range(40, 47)):
        u = alloc(0xa0)
        call(0x469f80, (), ecx=u)
        assert call(0x46bd30, (2, 2, 0, kind, 0x3de, 0), ecx=u) is not None, kind
        w, c = rd32(u + 4), rd32(u + 8)
        if w == 0:  # kind 46, the pod: no weapon -> offence 0, scope "n/a" (0x46b4b0)
            print(f"    ({kind}, 0, {rds32(u + 0x34)}, -1, -1, {rds32(c + 0x18)}),"); continue
        off = call(0x46b440, (), ecx=u) // 10          # page code 0x43d2e4..: raw / 10
        print(f"    ({kind}, {off}, {rds32(u + 0x34)}, {rds32(w + 0x18)}, {rds32(w + 0x1c)}, {rds32(c + 0x18)}),")
    print("// turrets 1-5: unit kinds 109..113 (the sentry page maps kind 25.. to them): offence, scope; defence = 0x4099a0 hit points")
    for kind in range(109, 114):
        u = alloc(0xa0)
        call(0x469f80, (), ecx=u)
        call(0x46bd30, (2, 2, 0, kind, 0x3de, 0), ecx=u)   # stops late (chassis path) but the weapon is built
        w = rd32(u + 4)
        off = call(0x46b440, (), ecx=u) // 10
        a, b = alloc(16), alloc(16)
        call(0x4099a0, (kind - 84, a, b))
        print(f"    ({kind - 84}, {off}, {rds32(a)}, {rds32(w + 0x18)}, {rds32(w + 0x1c)}),")
    print("// buildings 100..108 hit points from 0x4099a0 (shown / 100)")
    for kind in range(100, 109):
        a, b = alloc(16), alloc(16)
        call(0x4099a0, (kind, a, b))
        print(f"    ({kind}, {rds32(a)}),")
    print("// air forces 30..34: (kind, defence [+0x2c], speed field [+0x24], code [+0x28]) from 0x467ee0")
    for kind in range(30, 35):
        a = alloc(0xb4)
        call(0x4671a0, (), ecx=a)
        call(0x467ee0, (kind, 0xaa0, 0x460, 0), ecx=a)
        print(f"    ({kind}, {rds32(a + 0x2c)}, {rds32(a + 0x24)}, {rds32(a + 0x28)}),")
