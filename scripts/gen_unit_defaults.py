#!/usr/bin/env python3
"""Runs the exe's unit initialiser `0x46bd30` (stdcall(x, y, player, kind, slot, handle) on a fresh Unit object; it builds the Top with
`0x4796f0` + `0x479eb0` and the Chassis with `0x46e250` + `0x46ff50`) for every unit kind and prints the serialised fields it sets as a
Rust table (`UNIT_DEFAULTS` in `crates/opensow-game/src/sim/unit_defaults.rs`).

The sprite sizes (top `+0x64/+0x68`, chassis `+0x20/+0x24`) come from the sprite sheets of the install, so the sheet pointer tables
(`0x575770` tops, `0x593b30` chassis) are filled with a fake first frame whose header words differ between two runs; every field that
changes between the runs is a *size field* and is left out of the table (the bridge fills them from the install, `SpriteSizes`).

    /tmp/v/bin/python scripts/gen_unit_defaults.py "<install>/State of War.exe" target/release/opensow > crates/opensow-game/src/sim/unit_defaults.rs
"""
import os, struct, sys
from savestore_lib import *
from unicorn.x86_const import UC_X86_REG_EIP

HANDLE = 0x1234


def cdecl_ret(uc, value):
    uc.reg_write(UC_X86_REG_EAX, value)
    ret_to(uc, 0)


def memcpy_(uc):
    d, sr, n = arg(uc, 0), arg(uc, 1), arg(uc, 2)
    mu.mem_write(d, bytes(mu.mem_read(sr, n)))
    cdecl_ret(uc, d)


def memset_(uc):
    d, v, n = arg(uc, 0), arg(uc, 1), arg(uc, 2)
    mu.mem_write(d, bytes([v & 0xFF]) * n)
    cdecl_ret(uc, d)


def op_new(uc):
    a = alloc(arg(uc, 0))
    mu.mem_write(a, b"\0" * arg(uc, 0))
    cdecl_ret(uc, a)


stub(0x47EDA8, memcpy_)
stub(0x47EDB4, memset_)
stub(0x47D315, op_new)
stub(0x47D31B, op_new)  # operator new[]
stub(0x47D30F, lambda uc: cdecl_ret(uc, 0))  # operator delete (a kind without a top deletes the one it built)
stub(0x437B10, lambda uc: (uc.reg_write(UC_X86_REG_EAX, 7), ret_to(uc, 0)))  # visual rand(n): the hover phase, set by the bridge

FRAME = alloc(0x40)  # the fake first frame of every sheet: header words +8 / +0xa are the "extra" words of sprite.rs


def run(kind, marker):
    reset_heap()
    global FRAME
    FRAME = alloc(0x40)
    mu.mem_write(FRAME, b"\0" * 0x40)
    mu.mem_write(FRAME + 8, struct.pack("<HH", marker, (marker + 0x111) & 0xFFFF))
    for i in range(25):
        w32(0x575770 + 0x258 * i, FRAME)
    for i in range(6):
        w32(0x593B30 + 0x320 * i, FRAME)
    unit = alloc(0xa0)
    mu.mem_write(unit, b"\0" * 0xa0)
    sp = STACK + 0x100000 - 0x1000
    for a in reversed([5, 6, int(os.environ.get('PLAYER', '1')), kind, 0, HANDLE]):
        sp -= 4
        mu.mem_write(sp, struct.pack("<I", a))
    sp -= 4
    mu.mem_write(sp, struct.pack("<I", RET))
    mu.reg_write(UC_X86_REG_ESP, sp)
    mu.reg_write(UC_X86_REG_ECX, unit)
    try:
        mu.emu_start(0x46BD30, RET, count=3_000_000)
    except Exception as ex:
        sp = mu.reg_read(UC_X86_REG_ESP)
        sys.exit(f"kind {kind}: {ex} at {mu.reg_read(UC_X86_REG_EIP):#x}, stack {[hex(r32(sp + 4 * i)) for i in range(5)]}")
    out = {}

    def grab(cls, addr, tag, extra_words=()):
        for k, off in layout[cls]:
            if k == "b":
                out[(tag, off)] = mu.mem_read(addr + off, 1)[0] == 1
            else:
                out[(tag, off)] = r32(addr + off)
        for off in extra_words:
            out[(tag, off)] = r32(addr + off)

    grab("Unit", unit, "unit")
    top, chassis = r32(unit + 4), r32(unit + 8)
    if top:
        grab("Top", top, "top", [0x94 + 4 * i for i in range(10)] + [0xcc + 0x10 * i + 4 * k for i in range(20) for k in range(4)])
        grab("Weapon", top + 8, "topweapon")
    if chassis:
        grab("Chassis", chassis, "chassis")
        grab("Order", chassis + 0xd8, "order")
        if r32(chassis + 0xc) == 0x28:
            grab("Weapon", chassis + 0x104, "chassisweapon")
    return out, bool(top), bool(chassis)


KINDS = list(range(1, 16)) + list(range(40, 47)) + [109, 110, 111, 112, 113]
SKIP = {("unit", 0x14), ("unit", 0x18), ("unit", 0x84), ("unit", 0x3c), ("unit", 0x40), ("unit", 0x44), ("chassis", 0x14), ("chassis", 0x10)}
def sext16(v):
    v &= 0xFFFF
    return v - 0x10000 if v & 0x8000 else v


# the size formulas `formats::units::SheetSizes` implements, checked against the exe for two marker values
for marker in (0x1000, 0xFFFF, 0x7FFF):
    out, _, _ = run(5, marker)
    w, h = marker, (marker + 0x111) & 0xFFFF
    assert out[("top", 0x64)] == sext16(w + 1) & 0xFFFFFFFF, (marker, out[("top", 0x64)])
    assert out[("top", 0x68)] == sext16(h + 1) & 0xFFFFFFFF
    assert out[("chassis", 0x20)] == (sext16(w + 1) + 1) & 0xFFFFFFFF
    assert out[("chassis", 0x24)] == (sext16(h + 1) + 1) & 0xFFFFFFFF
print("//! Generated by scripts/gen_unit_defaults.py from the exe's unit initialiser `0x46bd30`; do not edit by hand.")
print()
print("/// Which record of a unit a table row belongs to.")
print("#[derive(Clone, Copy, PartialEq, Eq, Debug)]")
print("pub enum Part { Unit, Top, TopWeapon, Chassis, Order, ChassisWeapon }")
print()
print("/// One row of a unit's table: `(part, offset, value)`.")
print("pub type Row = (Part, u32, u32);")
print("/// One unit kind's table: `(kind, has top, has chassis, rows)`.")
print("pub type UnitDefault = (i32, bool, bool, &'static [Row]);")
print()
print("/// `(kind, has top, has chassis, rows)`; a row is `(part, offset, value)`, zeros left out. The sprite size fields (top `+0x64/+0x68`,")
print("/// chassis `+0x20/+0x24`) are not in it: they depend on the install's sprite sheets.")
print("pub const UNIT_DEFAULTS: &[UnitDefault] = &[")
PART = {"unit": "Unit", "top": "Top", "topweapon": "TopWeapon", "chassis": "Chassis", "order": "Order", "chassisweapon": "ChassisWeapon"}
size_fields = set()
for kind in KINDS:
    a, has_top, has_ch = run(kind, 0x1000)
    b, _, _ = run(kind, 0x2000)
    rows = []
    for key in sorted(a, key=lambda k: (list(PART).index(k[0]), k[1])):
        if a[key] != b.get(key):
            size_fields.add(key)
            continue
        if key in SKIP or not a[key]:
            continue
        rows.append((PART[key[0]], key[1], int(a[key])))
    print(f"    ({kind}, {str(has_top).lower()}, {str(has_ch).lower()}, &[" + ", ".join(f"(Part::{p}, {o:#x}, {v:#x})" for p, o, v in rows) + "]),")
print("];")
sys.stderr.write(f"size-dependent fields: {sorted((k[0], hex(k[1])) for k in size_fields)}\n")
