//! The skirmish simulation: units walk, weapon tops aim and fire, bullets fly and explode, structures take damage.
//!
//! Everything here is pure (no I/O, no rendering) and built from the decoded game rules: chassis animation
//! (`anim`), weapon tops (`aim`), target search over range rings (`rings`), bullet paths and area damage
//! (`projectile`). Values the exe analysis has not produced are placeholders and marked `PLACEHOLDER`:
//! movement speed, the weapons of static turrets and the enemy's behaviour.
//!
//! This file holds the data types (`World`, `Unit`, `Structure`, `Bullet`, ...), the per-tick driver `World::step`
//! and small shared helpers (terrain queries, random numbers, sounds and messages). The rest of `World`'s methods
//! live in submodules, one per subject:
//!
//! | module | what it does |
//! |---|---|
//! | `setup` | builds a world from a level, adds structures and units |
//! | `orders` | the player's selection and commands |
//! | `movement` | path search, avoidance and a unit's per-tick step |
//! | `combat` | target search, turrets, firing, bullets, explosions |
//! | `destruction` | building destruction, corpses, wrecks, nuclear blasts |
//! | `advancer_actions` | capture / repair / upgrade beams, satellites |
//! | `economy` | production, income, tech levels, turret building |
//! | `air_strikes` | aircraft and carryall airlifts |
//! | `mission` | win / lose rules, mission scripts, reinforcements |
//! | `tutorial` | the tutorial mission's script |
//! | `computer` | the computer opponent's turn; its planners are `defence`, `advancer_ai`, `airlift_ai`, `air_ai` |
//! | `savestate` | conversion to and from the original savegame stream |
//!
//! Methods a submodule defines for the others are `pub(super)`: visible inside `sim` only.

