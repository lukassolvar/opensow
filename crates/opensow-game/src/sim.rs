/// A custom map's convoy (not in the original, which scripts the pods of missions 3 and 8 by mission number): the cells the
/// human's pods walk through in order, the last one the middle of the 3x3 goal zone.
#[derive(Debug, Clone, PartialEq, Eq, Default, serde::Serialize, serde::Deserialize)]
pub struct Convoy {
    /// The cells the pods walk through, in order; the last one is the goal.
    pub route: Vec<(i32, i32)>,
    /// Per pod (unit id): the index of the route cell it walks to.
    pub next: Vec<(u32, usize)>,
    /// The human had pods at the start (losing them all loses).
    pub had_pods: bool,
}

impl Convoy {
    /// The goal cell (the middle of the 3x3 goal zone), `None` without a route.
    pub fn goal(&self) -> Option<(i32, i32)> {
        self.route.last().copied()
    }

    /// Whether `cell` lies in the goal zone (the goal cell and its eight neighbours).
    pub fn in_goal(&self, cell: (i32, i32)) -> bool {
        self.goal().is_some_and(|g| (g.0 - cell.0).abs() <= 1 && (g.1 - cell.1).abs() <= 1)
    }
}

